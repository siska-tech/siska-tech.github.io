// --- カスタム例文ファイルのパース --------------------------------------------
// .json: [{title, items}] もしくは {lessons:[...]}
// .txt/.md: 「# 見出し」=レッスン名、その他の非空行=例文、``` / ※ / --- は無視
function parseLessonFile(name, text) {
  const lower = name.toLowerCase();
  if (lower.endsWith(".json")) {
    const data = JSON.parse(text);
    const arr = Array.isArray(data) ? data : data.lessons;
    return arr
      .map((l) => ({ title: String(l.title || "custom"), items: (l.items || []).map(String) }))
      .filter((l) => l.items.length);
  }
  // テキスト/Markdown
  const out = [];
  let cur = null;
  let inFence = false;
  for (let raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line.startsWith("```")) { inFence = !inFence; continue; }
    if (!line || line === "---" || line.startsWith("※")) continue;
    const h = line.match(/^#+\s+(.*)$/);
    if (h) { cur = { title: h[1].trim(), items: [] }; out.push(cur); continue; }
    if (!cur) { cur = { title: "custom", items: [] }; out.push(cur); }
    cur.items.push(line);
  }
  return out.filter((l) => l.items.length);
}
